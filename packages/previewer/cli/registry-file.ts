import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';

export interface ScenarioExport {
  /** Path of the `*.scenarios.ts` file, relative to the registry file, posix, without extension. */
  readonly importPath: string;
  readonly exportName: string;
}

export class DuplicateScenarioExportName extends Error {
  override readonly name = 'DuplicateScenarioExportName';

  constructor(
    readonly exportName: string,
    readonly importPaths: readonly string[],
  ) {
    super(`"${exportName}" is exported by more than one scenarios file: ${importPaths.join(', ')}. Rename one.`);
  }
}

const SCENARIOS_FILE_SUFFIX = '.scenarios.ts';
const SKIPPED_DIRECTORIES = new Set(['node_modules', 'dist', 'out-tsc', 'coverage']);
const DEFINE_SCENARIOS_EXPORT = /export\s+const\s+([A-Za-z_$][\w$]*)\s*(?::[^=]+)?=\s*defineScenarios\s*[<(]/g;

export const GENERATED_HEADER = '// Generated by ligeirinho-preview-registry. Do not edit: run it again instead.';

export async function findScenarioFiles(rootDirectory: string): Promise<string[]> {
  const directoryEntries = await readdir(rootDirectory, { withFileTypes: true, recursive: true });
  return directoryEntries
    .filter((directoryEntry) => directoryEntry.isFile() && directoryEntry.name.endsWith(SCENARIOS_FILE_SUFFIX))
    .map((directoryEntry) => path.join(directoryEntry.parentPath, directoryEntry.name))
    .filter((filePath) => !isInSkippedDirectory(path.relative(rootDirectory, filePath)))
    .sort();
}

function isInSkippedDirectory(relativeFilePath: string): boolean {
  const directories = relativeFilePath.split(path.sep).slice(0, -1);
  return directories.some((directory) => directory.startsWith('.') || SKIPPED_DIRECTORIES.has(directory));
}

export function findExportNames(sourceText: string): string[] {
  return [...sourceText.matchAll(DEFINE_SCENARIOS_EXPORT)].flatMap((match) => (match[1] === undefined ? [] : [match[1]]));
}

export function toImportPath(registryFilePath: string, scenariosFilePath: string): string {
  const relativePath = path.relative(path.dirname(registryFilePath), scenariosFilePath).split(path.sep).join('/');
  const withoutExtension = relativePath.replace(/\.ts$/, '');
  return withoutExtension.startsWith('.') ? withoutExtension : `./${withoutExtension}`;
}

export async function collectScenarioExports(rootDirectory: string, registryFilePath: string): Promise<ScenarioExport[]> {
  const scenarioFiles = await findScenarioFiles(rootDirectory);
  const exportsPerFile = await Promise.all(
    scenarioFiles.map(async (scenariosFilePath) => {
      const importPath = toImportPath(registryFilePath, scenariosFilePath);
      const exportNames = findExportNames(await readFile(scenariosFilePath, 'utf8'));
      return exportNames.map((exportName) => ({ importPath, exportName }));
    }),
  );
  return sortScenarioExports(exportsPerFile.flat());
}

export function sortScenarioExports(scenarioExports: readonly ScenarioExport[]): ScenarioExport[] {
  return [...scenarioExports].sort(
    (left, right) =>
      compareText(left.importPath, right.importPath) || compareText(left.exportName, right.exportName),
  );
}

function compareText(left: string, right: string): number {
  if (left === right) {
    return 0;
  }
  return left < right ? -1 : 1;
}

/** @throws DuplicateScenarioExportName */
export function renderRegistry(scenarioExports: readonly ScenarioExport[]): string {
  assertUniqueExportNames(scenarioExports);
  const importLines = scenarioExports.map(
    (scenarioExport) => `import { ${scenarioExport.exportName} } from '${scenarioExport.importPath}';`,
  );
  return [
    GENERATED_HEADER,
    "import type { ScenarioRegistry } from '@ligeirinho/previewer';",
    ...importLines,
    '',
    `export const scenarioRegistry: ScenarioRegistry = ${renderArray(scenarioExports)};`,
    '',
  ].join('\n');
}

function renderArray(scenarioExports: readonly ScenarioExport[]): string {
  if (scenarioExports.length === 0) {
    return '[]';
  }
  const itemLines = scenarioExports.map((scenarioExport) => `  ${scenarioExport.exportName},`);
  return ['[', ...itemLines, ']'].join('\n');
}

function assertUniqueExportNames(scenarioExports: readonly ScenarioExport[]): void {
  for (const scenarioExport of scenarioExports) {
    const sameNameExports = scenarioExports.filter((candidate) => candidate.exportName === scenarioExport.exportName);
    if (sameNameExports.length > 1) {
      throw new DuplicateScenarioExportName(
        scenarioExport.exportName,
        sameNameExports.map((sameNameExport) => sameNameExport.importPath),
      );
    }
  }
}
