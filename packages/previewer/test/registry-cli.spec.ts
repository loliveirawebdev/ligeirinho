import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { promisify } from 'node:util';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import {
  InvalidRegistryArguments,
  checkRegistry,
  parseRegistryArguments,
  writeRegistry,
} from '../cli/registry-command';
import { DuplicateScenarioExportName, findExportNames, renderRegistry, toImportPath } from '../cli/registry-file';

const runFile = promisify(execFile);
const packageDirectory = path.resolve(import.meta.dirname, '..');
const builtCli = path.join(packageDirectory, 'dist-cli', 'main.js');

let projectDirectory = '';

beforeEach(async () => {
  projectDirectory = await mkdtemp(path.join(tmpdir(), 'ligeirinho-registry-'));
});

afterEach(async () => {
  await rm(projectDirectory, { recursive: true, force: true });
});

async function writeProjectFile(relativePath: string, content: string): Promise<void> {
  const filePath = path.join(projectDirectory, relativePath);
  await mkdir(path.dirname(filePath), { recursive: true });
  await writeFile(filePath, content, 'utf8');
}

function scenariosSource(exportName: string): string {
  return `import { defineScenarios } from '@ligeirinho/previewer';\nexport const ${exportName} = defineScenarios<Model>({});\n`;
}

function argumentsFor(...extraArguments: string[]) {
  return parseRegistryArguments(['--root', 'src', '--out', 'src/app/preview.registry.ts', ...extraArguments], projectDirectory);
}

describe('findExportNames', () => {
  it('finds every exported defineScenarios constant, with or without type arguments or annotations', () => {
    const source = [
      'export const taskListScenarios = defineScenarios<TaskListViewModel>({',
      'export const profileScenarios: ScenarioEntry<Profile> = defineScenarios({',
      'const privateScenarios = defineScenarios({',
      'export const notScenarios = somethingElse({',
    ].join('\n');
    expect(findExportNames(source)).toEqual(['taskListScenarios', 'profileScenarios']);
  });
});

describe('toImportPath', () => {
  it('is relative to the registry file, posix, without extension', () => {
    expect(toImportPath('/project/src/app/preview.registry.ts', '/project/src/app/tasks/task-list.scenarios.ts')).toBe(
      './tasks/task-list.scenarios',
    );
    expect(toImportPath('/project/src/app/preview.registry.ts', '/project/src/shared/card.scenarios.ts')).toBe(
      '../shared/card.scenarios',
    );
  });
});

describe('renderRegistry', () => {
  it('renders an empty registry', () => {
    expect(renderRegistry([])).toContain('export const scenarioRegistry: ScenarioRegistry = [];');
  });

  it('rejects two exports with the same name', () => {
    expect(() =>
      renderRegistry([
        { importPath: './a.scenarios', exportName: 'cardScenarios' },
        { importPath: './b.scenarios', exportName: 'cardScenarios' },
      ]),
    ).toThrow(DuplicateScenarioExportName);
  });
});

describe('writeRegistry', () => {
  it('writes a sorted registry with a generated header, skipping node_modules and hidden folders', async () => {
    await writeProjectFile('src/app/tasks/task-list.scenarios.ts', scenariosSource('taskListScenarios'));
    await writeProjectFile('src/app/account/profile.scenarios.ts', scenariosSource('profileScenarios'));
    await writeProjectFile('src/node_modules/library/ignored.scenarios.ts', scenariosSource('ignoredScenarios'));
    await writeProjectFile('src/.cache/ignored.scenarios.ts', scenariosSource('hiddenScenarios'));
    await writeProjectFile('src/app/tasks/task-list.view.ts', 'export class TaskListView {}\n');

    const outcome = await writeRegistry(argumentsFor());

    expect(outcome.exitCode).toBe(0);
    expect(await readFile(path.join(projectDirectory, 'src/app/preview.registry.ts'), 'utf8')).toBe(
      [
        '// Generated by ligeirinho-preview-registry. Do not edit: run it again instead.',
        "import type { ScenarioRegistry } from '@ligeirinho/previewer';",
        "import { profileScenarios } from './account/profile.scenarios';",
        "import { taskListScenarios } from './tasks/task-list.scenarios';",
        '',
        'export const scenarioRegistry: ScenarioRegistry = [',
        '  profileScenarios,',
        '  taskListScenarios,',
        '];',
        '',
      ].join('\n'),
    );
  });
});

describe('checkRegistry', () => {
  it('passes when the registry file is up to date', async () => {
    await writeProjectFile('src/app/tasks/task-list.scenarios.ts', scenariosSource('taskListScenarios'));
    await writeRegistry(argumentsFor());

    expect((await checkRegistry(argumentsFor('--check'))).exitCode).toBe(0);
  });

  it('fails when a scenarios file was added after generation', async () => {
    await writeProjectFile('src/app/tasks/task-list.scenarios.ts', scenariosSource('taskListScenarios'));
    await writeRegistry(argumentsFor());
    await writeProjectFile('src/app/account/profile.scenarios.ts', scenariosSource('profileScenarios'));

    expect((await checkRegistry(argumentsFor('--check'))).exitCode).toBe(1);
  });

  it('fails when the registry file does not exist', async () => {
    await writeProjectFile('src/app/tasks/task-list.scenarios.ts', scenariosSource('taskListScenarios'));

    expect((await checkRegistry(argumentsFor('--check'))).exitCode).toBe(1);
  });
});

describe('parseRegistryArguments', () => {
  it('requires --root and --out', () => {
    expect(() => parseRegistryArguments(['--root', 'src'], projectDirectory)).toThrow(InvalidRegistryArguments);
  });

  it('rejects unknown options', () => {
    expect(() => parseRegistryArguments(['--root', 'src', '--out', 'x.ts', '--watch'], projectDirectory)).toThrow(
      InvalidRegistryArguments,
    );
  });
});

describe('built bin', () => {
  it('exits 1 with --check on a stale registry and 0 after regenerating', async () => {
    await writeProjectFile('src/app/tasks/task-list.scenarios.ts', scenariosSource('taskListScenarios'));
    const commandArguments = [builtCli, '--root', 'src', '--out', 'src/app/preview.registry.ts'];

    await expect(runFile('node', [...commandArguments, '--check'], { cwd: projectDirectory })).rejects.toMatchObject({
      code: 1,
    });
    await runFile('node', commandArguments, { cwd: projectDirectory });
    await expect(runFile('node', [...commandArguments, '--check'], { cwd: projectDirectory })).resolves.toBeDefined();
  });

  it('keeps the demo registry up to date', async () => {
    await expect(
      runFile('node', [builtCli, '--root', 'demo/src', '--out', 'demo/src/app/preview.registry.ts', '--check'], {
        cwd: packageDirectory,
      }),
    ).resolves.toBeDefined();
  });
});
